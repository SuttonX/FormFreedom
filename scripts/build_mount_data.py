#!/usr/bin/env python3
"""Derive mounted-cast facts from the same pinned stock 12340 DBC as form data.

Usage: python3 scripts/build_mount_data.py /path/to/Spell.dbc
Source: Torrer/TrinityCore-3.3.5-data ac753a9b849e578ce2295d15125c8eb17e1b22c0.
Only numeric restriction facts are emitted; no DBC binary or spell text is bundled.
"""
from pathlib import Path
import hashlib
import struct
import sys

data = Path(sys.argv[1]).read_bytes()
magic, count, fields, size, strings = struct.unpack_from('<4s4I', data)
assert magic == b'WDBC' and fields == 234 and size == 936
assert len(data) == 20 + count * size + strings
facts = []
for offset in range(20, 20 + count * size, size):
    spell_id, _, _, _, attributes = struct.unpack_from('<5I', data, offset)
    # Spell::CheckCast exempts passive spells and ALLOW_WHILE_MOUNTED.
    blocked = not (attributes & (0x40 | 0x01000000))
    facts.append((spell_id, blocked))
assert len({spell_id for spell_id, _ in facts}) == count
lines = [
    '-- Stock 3.3.5 build-12340 mounted-cast facts; see CREDITS.md.',
    '-- Generated by scripts/build_mount_data.py; true=blocked, false=allowed/passive.',
    '-- Spell.dbc SHA256: ' + hashlib.sha256(data).hexdigest(),
    'local _, ns = ...',
    'if not ns.enabled then return end',
    'ns.mountRestrictions = {',
]
lines += ['[%d]=%s,' % (spell_id, str(blocked).lower()) for spell_id, blocked in sorted(facts)]
lines.append('}')
output = Path(__file__).resolve().parents[1] / 'MountRestrictions.lua'
output.write_text('\n'.join(lines) + '\n')
print('Mounted-cast facts: %d spells (%d blocked)' % (count, sum(blocked for _, blocked in facts)))
